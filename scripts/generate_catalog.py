def I(name, desc, cat, price, unit, serves, tags="", spice=0):
    """Linha da tabela de itens: nome, descrição, categoria, preço, unidade, serve, tags, picância."""
    return {
        "name": name,
        "description": desc,
        "category": cat,
        "price": price,
        "unit": unit,
        "serves": serves,
        "tags": tags,
        "spice": spice,
    }


def price_90(value: float) -> float:
    """Arredonda para o padrão de varejo 'R$ xx,90'."""
    return math.floor(value) + 0.90


def pizza(name, desc, price_grande, tags="", spice=0, cat=PRA):
    """Expande um sabor de pizza em dois tamanhos."""
    return [
        I(f"Pizza {name} média", desc, cat, price_90(price_grande * 0.78),
          "pizza média (6 fatias)", 2, tags, spice),
        I(f"Pizza {name} grande", desc, cat, price_grande,
          "pizza grande (8 fatias)", 3, tags, spice),
    ]


