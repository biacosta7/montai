def parse_tags(codes: str) -> list[DietTag]:
    tags = {TAG_CODES[c] for c in codes.split()}
    # Regra de domínio: vegano implica vegetariano e sem lactose.
    if DietTag.VEGANO in tags:
        tags |= {DietTag.VEGETARIANO, DietTag.SEM_LACTOSE}
    return [t for t in TAG_ORDER if t in tags]


def build_catalog() -> Catalog:
    stores: list[Store] = []
    items: list[Item] = []
    for store, rows in STORES:
        stores.append(store)
        for n, row in enumerate(rows, start=1):
            items.append(Item(
                id=f"{store.id}-{n:03d}",
                store_id=store.id,
                name=row["name"],
                description=row["description"],
                category=row["category"],
                price=round(row["price"], 2),
                unit=row["unit"],
                serves=row["serves"],
                diet=parse_tags(row["tags"]),
                spice_level=row["spice"],
            ))
    return Catalog(version=CATALOG_VERSION, stores=stores, items=items)


def render(catalog: Catalog) -> str:
    return json.dumps(catalog.model_dump(mode="json"), ensure_ascii=False, indent=2) + "\n"


def main() -> None:
    catalog = build_catalog()
    CATALOG_PATH.write_text(render(catalog), encoding="utf-8")
    print(f"{len(catalog.stores)} estabelecimentos, {len(catalog.items)} itens -> {CATALOG_PATH}")


if __name__ == "__main__":
    main()
